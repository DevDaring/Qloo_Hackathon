/**
 * InteractiveMedia — one interaction for every product photo, flyer, creative
 * thumbnail and video poster:
 *  rest: stable aspect ratio + subtle border + caption
 *  hover (pointer): image scales ~1.05 inside an overflow-hidden frame, accent ring + soft glow fade in (200 ms)
 *  keyboard focus: visible focus ring + the same affordance
 *  activate (click / Enter / tap): accessible full-size preview with close, prev/next, Escape and focus restore
 *  reduced motion: no scale or animated glow, static border change only
 */
import { useCallback, useEffect, useId, useState, type ReactNode } from 'react';
import { createPortal } from 'react-dom';
import { AnimatePresence, motion } from 'framer-motion';
import { ChevronLeft, ChevronRight, Expand, X } from 'lucide-react';
import { cn } from '../lib/format';
import { useDialog } from './Overlay';

export interface MediaItem {
  src: string;
  alt: string;
  caption?: ReactNode;
  kind?: 'image' | 'video';
  poster?: string;
  /** text shown in the lightbox under the media (e.g. "Generated by LaunchLens · v2") */
  meta?: ReactNode;
}

/** Shared frame classes so non-image tiles (e.g. video posters drawn by other components) look identical. */
export const mediaFrame =
  'group/media relative block overflow-hidden rounded-xl border border-line bg-surface2 outline-none transition-[box-shadow,border-color] duration-200 ' +
  'hover:border-brand/60 hover:shadow-[0_0_0_3px_rgb(var(--primary)/0.22),0_10px_30px_-10px_rgb(var(--primary)/0.55)] ' +
  'focus-visible:border-accent focus-visible:shadow-[0_0_0_3px_rgb(var(--secondary)/0.45)] ' +
  'motion-reduce:transition-none';
export const mediaImg = 'h-full w-full transition-transform duration-200 ease-out group-hover/media:scale-[1.05] group-focus-visible/media:scale-[1.05] motion-reduce:transition-none motion-reduce:group-hover/media:scale-100 motion-reduce:group-focus-visible/media:scale-100';

export function InteractiveMedia({
  items,
  index = 0,
  className,
  frameClassName,
  aspect = 'aspect-square',
  fit = 'cover',
  showCaption = true,
  badge,
  actions,
  onOpen,
}: {
  items: MediaItem[];
  index?: number;
  className?: string;
  frameClassName?: string;
  aspect?: string;
  fit?: 'cover' | 'contain';
  showCaption?: boolean;
  badge?: ReactNode;
  /** extra actions rendered in the lightbox for the current item */
  actions?: (item: MediaItem, i: number) => ReactNode;
  /** override: open something else (e.g. a details drawer) instead of the lightbox */
  onOpen?: () => void;
}) {
  const [open, setOpen] = useState<number | null>(null);
  const it = items[index];
  if (!it) return null;
  const isVideo = it.kind === 'video';
  return (
    <figure className={cn('min-w-0', className)}>
      <button
        type="button"
        onClick={() => (onOpen ? onOpen() : setOpen(index))}
        className={cn(mediaFrame, aspect, 'w-full', frameClassName)}
        aria-label={`Open preview: ${it.alt}`}
      >
        {isVideo ? (
          <img src={it.poster} alt="" className={cn(mediaImg, fit === 'cover' ? 'object-cover' : 'object-contain')} loading="lazy" />
        ) : (
          <img src={it.src} alt={it.alt} className={cn(mediaImg, fit === 'cover' ? 'object-cover' : 'object-contain')} loading="lazy" />
        )}
        {/* soft inner glow (pseudo-layer, no layout change) */}
        <span
          aria-hidden
          className="pointer-events-none absolute inset-0 rounded-[inherit] opacity-0 shadow-[inset_0_0_0_2px_rgb(var(--primary)/0.65),inset_0_0_40px_rgb(var(--primary)/0.25)] transition-opacity duration-200 group-hover/media:opacity-100 group-focus-visible/media:opacity-100 motion-reduce:transition-none"
        />
        {/* visible affordance (touch users have no hover) */}
        <span aria-hidden className="absolute bottom-1.5 right-1.5 flex h-7 w-7 items-center justify-center rounded-lg bg-black/45 text-white backdrop-blur-sm">
          <Expand className="h-3.5 w-3.5" />
        </span>
        {badge && <span className="absolute left-1.5 top-1.5">{badge}</span>}
      </button>
      {showCaption && it.caption && <figcaption className="mt-1.5 text-xs text-muted">{it.caption}</figcaption>}
      <Lightbox items={items} index={open} onIndex={setOpen} actions={actions} />
    </figure>
  );
}

export function Lightbox({
  items,
  index,
  onIndex,
  actions,
}: {
  items: MediaItem[];
  index: number | null;
  onIndex: (i: number | null) => void;
  actions?: (item: MediaItem, i: number) => ReactNode;
}) {
  const open = index !== null;
  const close = useCallback(() => onIndex(null), [onIndex]);
  const ref = useDialog(open, close);
  const tid = useId();
  const n = items.length;
  const go = useCallback((d: number) => index !== null && n > 1 && onIndex((index + d + n) % n), [index, n, onIndex]);
  useEffect(() => {
    if (!open) return;
    const onKey = (e: KeyboardEvent) => {
      if (e.key === 'ArrowRight') go(1);
      if (e.key === 'ArrowLeft') go(-1);
    };
    window.addEventListener('keydown', onKey);
    return () => window.removeEventListener('keydown', onKey);
  }, [open, go]);
  const it = index !== null ? items[index] : null;
  return createPortal(
    <AnimatePresence>
      {open && it && (
        <div className="fixed inset-0 z-[90] flex items-center justify-center p-3 sm:p-8">
          <motion.div className="absolute inset-0 bg-[#060A14]/85 backdrop-blur-sm" initial={{ opacity: 0 }} animate={{ opacity: 1 }} exit={{ opacity: 0 }} onClick={close} aria-hidden />
          <motion.div
            ref={ref}
            role="dialog"
            aria-modal="true"
            aria-labelledby={tid}
            initial={{ opacity: 0, scale: 0.97 }}
            animate={{ opacity: 1, scale: 1 }}
            exit={{ opacity: 0, scale: 0.97 }}
            transition={{ duration: 0.2 }}
            className="relative flex max-h-full w-full max-w-5xl flex-col"
          >
            <div className="mb-2 flex items-center gap-2 text-white">
              <p id={tid} className="min-w-0 flex-1 truncate text-sm font-semibold">
                {it.alt}
              </p>
              {n > 1 && (
                <span className="text-xs text-white/60" aria-live="polite">
                  {index! + 1} / {n}
                </span>
              )}
              <button type="button" onClick={close} className="flex h-11 w-11 items-center justify-center rounded-xl bg-white/10 hover:bg-white/20" aria-label="Close preview">
                <X className="h-5 w-5" />
              </button>
            </div>
            <div className="relative flex min-h-0 flex-1 items-center justify-center">
              {it.kind === 'video' ? (
                <video key={it.src} src={it.src} poster={it.poster} controls autoPlay muted playsInline className="max-h-[75vh] max-w-full rounded-xl bg-black" aria-label={it.alt} />
              ) : (
                <img key={it.src} src={it.src} alt={it.alt} className="max-h-[75vh] max-w-full rounded-xl object-contain shadow-2xl" />
              )}
              {n > 1 && (
                <>
                  <button type="button" onClick={() => go(-1)} className="absolute left-0 top-1/2 flex h-11 w-11 -translate-y-1/2 items-center justify-center rounded-full bg-white/15 text-white hover:bg-white/25 sm:-left-14" aria-label="Previous">
                    <ChevronLeft className="h-5 w-5" />
                  </button>
                  <button type="button" onClick={() => go(1)} className="absolute right-0 top-1/2 flex h-11 w-11 -translate-y-1/2 items-center justify-center rounded-full bg-white/15 text-white hover:bg-white/25 sm:-right-14" aria-label="Next">
                    <ChevronRight className="h-5 w-5" />
                  </button>
                </>
              )}
            </div>
            {(it.caption || it.meta || actions) && (
              <div className="mt-3 flex flex-wrap items-center gap-3 rounded-xl bg-white/[0.06] px-4 py-2.5 text-sm text-white/85">
                <div className="min-w-0 flex-1">
                  {it.caption && <div>{it.caption}</div>}
                  {it.meta && <div className="text-xs text-white/60">{it.meta}</div>}
                </div>
                {actions?.(it, index!)}
              </div>
            )}
          </motion.div>
        </div>
      )}
    </AnimatePresence>,
    document.body,
  );
}
